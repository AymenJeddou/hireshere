export function href(lang: Lang, page: Page, country?: string): string {
  // Countries and fields are filters on the one search page: ?c=TN&f=engineering.
  if (page === "country") return `${SLUGS.search[lang]}?c=${(country ?? "").toUpperCase()}`;
  if (page === "field") {
    const [c, f] = (country ?? "").split("/");
    return `${SLUGS.search[lang]}?c=${c.toUpperCase()}&f=${f}`;
  }
  if (page === "job" || page === "company") return SLUGS[page][lang] + (country ?? "");
  return SLUGS[page][lang];
}

